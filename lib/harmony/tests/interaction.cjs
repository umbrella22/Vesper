'use strict';
const assert = require('node:assert/strict');
const path = require('node:path');
const { createLoader } = require('./support/load.cjs');
const load = createLoader(name => { throw new Error('Unexpected interaction import: ' + name); });
const { StageValuePump, StageTemporaryRate, stageGestureAxis } = load(path.resolve(__dirname, '../vesper-player-kit-arkui-ui/src/main/ets/Interaction.ets'));
const flush = async () => { for (let i = 0; i < 12; i++) await Promise.resolve(); };
(async () => {
  assert.equal(stageGestureAxis(10, 10), '', 'diagonal input waits for a clear axis');
  assert.equal(stageGestureAxis(12, 10), 'horizontal');
  assert.equal(stageGestureAxis(10, 12), 'vertical');
  let release; const applied = []; const failures = [];
  const pump = new StageValuePump(value => { applied.push(value); return new Promise(resolve => { release = resolve; }); }, error => failures.push(error));
  pump.submit(0.2); pump.submit(0.3); pump.submit(0.4);
  assert.deepEqual(applied, [0.2]); release(); await flush();
  assert.deepEqual(applied, [0.2, 0.4], 'intermediate pointer samples never form a command queue');
  pump.submit(0.9); pump.cancel(); release(); await flush();
  assert.deepEqual(applied, [0.2, 0.4], 'cancel drops the queued sample');
  let epoch = 'a'; const rates = []; let rateRelease;
  const temporary = new StageTemporaryRate(rate => { rates.push(rate); return rate === 2 ? new Promise(resolve => { rateRelease = resolve; }) : Promise.resolve(); }, () => epoch, error => failures.push(error));
  assert.equal(temporary.begin(1.25), true); assert.equal(temporary.begin(1.5), false);
  const restoration = temporary.end(); rateRelease(); await restoration;
  assert.deepEqual(rates, [2, 1.25], 'release during native apply restores the exact prior rate');
  temporary.begin(0.75); epoch = 'b'; const stale = temporary.end(); rateRelease(); await stale;
  assert.deepEqual(rates, [2, 1.25, 2], 'a new source never receives the old source rate');
  assert.deepEqual(failures, []);
  process.stdout.write(JSON.stringify({ status: 'PASS', suite: 'stage-interaction', contracts: ['axis arbitration', 'bounded latest-value input', 'cancel pending input', 'release during temporary rate apply', 'exact rate restoration', 'new epoch isolation'] }) + '\n');
})().catch(error => { console.error(error); process.exitCode = 1; });
