Uint8List decodeTinyAacFixture() {
  final bytes = base64Decode(_tinyAacFixtureBase64);
  if (bytes.lengthInBytes != tinyAacFixtureLength) {
    throw StateError(
      'Decoded subtitle media fixture has ${bytes.lengthInBytes} bytes; '
      'expected $tinyAacFixtureLength.',
    );
  }
  return bytes;
}

Future<File> writeTinyAacFixture(Directory directory) async {
